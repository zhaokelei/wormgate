import { chromium } from 'playwright-core'
const b = await chromium.launch({ channel: 'msedge', headless: true })
const p = await (await b.newContext({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 2, colorScheme: 'dark' })).newPage()
await p.goto('http://127.0.0.1:17300/next/login', { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(900)
const brand = await p.evaluate(() => document.body.innerText.slice(0, 200).replace(/\n+/g, ' | '))
await p.screenshot({ path: '../.run/wormgate-login.png' })
await p.fill('input[autocomplete=username]', 'admin')
await p.fill('input[autocomplete=current-password]', 'i18n-admin-1234')
await p.keyboard.press('Enter')
await p.waitForTimeout(1800)
const shell = await p.evaluate(() => (document.querySelector('.ant-layout-sider')?.innerText || '').replace(/\n+/g, ' | '))
console.log('login card:', brand)
console.log('sidebar:', shell)
await b.close()
